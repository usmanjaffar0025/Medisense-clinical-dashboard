type ClientRow = [
  id: string,
  name: string,
  age: number,
  service: string,
  funding: Funding,
  tenureMonths: number,
  lastSession: string,
  next: string,
  complexity: Complexity,
];

function routineClient([
  id,
  name,
  age,
  service,
  funding,
  tenureMonths,
  lastSession,
  next,
  complexity,
]: ClientRow): CaseloadClient {
  return {
    id,
    name,
    age,
    service,
    funding,
    tenureMonths,
    lastSession,
    nextAppointment: { kind: "booked", label: next },
    complexity,
    documentation: { kind: "complete" },
    attention: { kind: "none" },
    filters: [],
  };
}

